// Release signing comes from environment variables so the keystore never lives in the repo.
// Locally: export DABBULU_KEYSTORE_FILE=/path/to/dabbulu-release.jks and the three passwords/alias.
// On GitHub Actions: the workflow writes the keystore from repository secrets.
val releaseKeystore: String? = System.getenv("DABBULU_KEYSTORE_FILE")

android {
    namespace = "app.dabbulu"
    compileSdk = 37

    defaultConfig {
        applicationId = "app.dabbulu"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = System.getenv("DABBULU_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("DABBULU_KEY_ALIAS")
                keyPassword = System.getenv("DABBULU_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            if (releaseKeystore != null) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
        }
    }
}

